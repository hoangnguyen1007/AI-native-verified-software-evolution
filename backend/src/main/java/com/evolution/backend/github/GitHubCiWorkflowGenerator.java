package com.evolution.backend.github;

import com.evolution.analysis.contract.common.ContentDigest;
import java.util.*;

/**
 * Generates ready-to-use GitHub Actions CI workflows for Evo Architecture Quality Gate
 * and GitHub Code Scanning SARIF 2.1.0 upload.
 */
public final class GitHubCiWorkflowGenerator {
    public static final String WORKFLOW_PATH = ".github/workflows/evo-architecture-gate.yml";

    public record GeneratedWorkflow(String filename, String yaml, ContentDigest sha256) {
        public Map<String, Object> toView() {
            var map = new LinkedHashMap<String, Object>();
            map.put("filename", filename);
            map.put("yaml", yaml);
            map.put("sha256", sha256.value());
            return map;
        }
    }

    private GitHubCiWorkflowGenerator() {
    }

    public static GeneratedWorkflow generate(
            GitHubCoordinates.Coordinates coords,
            String defaultBranch,
            boolean failOnMust,
            int minScore) {
        String branch = (defaultBranch == null || defaultBranch.isBlank()) ? "main" : GitHubCoordinates.validateBranchName(defaultBranch);
        int clampedMin = Math.max(0, Math.min(100, minScore));
        String repoLabel = coords == null ? "repository" : coords.fullName();
        String yaml = """
                # Generated by Evo Architecture Intelligence for %s
                name: Evo Architecture Quality Gate

                on:
                  push:
                    branches: [ "%s" ]
                  pull_request:
                    branches: [ "%s" ]

                permissions:
                  contents: read
                  pull-requests: write
                  security-events: write
                  statuses: write

                concurrency:
                  group: evo-arch-${{ github.ref }}
                  cancel-in-progress: true

                jobs:
                  architecture-gate:
                    name: Architecture Score v2 & Policy Gate
                    runs-on: ubuntu-latest
                    steps:
                      - name: Checkout repository
                        uses: actions/checkout@v4
                        with:
                          fetch-depth: 0

                      - name: Set up JDK 21
                        uses: actions/setup-java@v4
                        with:
                          distribution: temurin
                          java-version: '21'

                      - name: Run Evo Passive Architecture Analysis & Score v2
                        env:
                          EVO_MIN_SCORE: "%d"
                          EVO_FAIL_ON_MUST: "%s"
                          GITHUB_TOKEN: ${{ secrets.GITHUB_TOKEN }}
                        run: |
                          mkdir -p .evo-out
                          java -jar "${{ vars.EVO_JAR_PATH || 'evo.jar' }}" analyze \\
                            --source . \\
                            --out .evo-out \\
                            --score-v2 \\
                            --sarif-out .evo-out/evo-architecture.sarif

                      - name: Upload SARIF to GitHub Code Scanning
                        if: always() && hashFiles('.evo-out/evo-architecture.sarif') != ''
                        uses: github/codeql-action/upload-sarif@v3
                        with:
                          sarif_file: .evo-out/evo-architecture.sarif
                          category: evo-architecture-intelligence
                """.formatted(repoLabel, branch, branch, clampedMin, failOnMust);
        return new GeneratedWorkflow(WORKFLOW_PATH, yaml, ContentDigest.sha256Utf8(yaml));
    }
}
